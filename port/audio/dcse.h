/* Dreamcast common sound effects in place of the PS2's.
 *
 * The PS2 disc stores most of the common effects (AFS01 #59 and #60: hits,
 * blocks, menu and round sounds) at 8 kHz; the Dreamcast disc's SE_COMN.BIN
 * holds the same recordings at 11-16 kHz.  Given the player's own copy of
 * that file (from their Dreamcast disc), dcse_apply() swaps those samples
 * into the PS2 banks as they load.  Everything else about the sounds (which
 * one plays, its pitch, envelope, volume, pan) stays the PS2 game's: the
 * sample is the same recording, only with the bandwidth the PS2 cut.
 *
 * The mapping (port/audio/dcse_map.h, generated by
 * port/tools/convert/dc_se_map.py) is by sample index; it is checked against
 * fingerprints of both banks and of SE_COMN.BIN, and every swapped sample's
 * length is checked too, so a different disc version leaves the PS2 sounds
 * as they are.  See port/docs/AUDIO.md section 9.
 *
 * SE_COMN.BIN: a Sega DTPK sound bank (sample table at header +0x3C:
 * u32 last index, then 16-byte records {u32 offset | 0x1000000 ADPCM,
 * u16 loop start, u16 loop end, u32 stereo, u32 bytes}), samples in Yamaha
 * 4-bit ADPCM as the AICA decodes it.
 */
#ifndef PORT_AUDIO_DCSE_H
#define PORT_AUDIO_DCSE_H
#include <stddef.h>
#include <stdint.h>

struct HdBank;

/* Load SE_COMN.BIN; returns the number of PS2 samples it can replace, or -1
 * (not that file / not the known version).  Replaces any earlier load. */
int dcse_load(const uint8_t *se_comn, size_t size);
int dcse_loaded(void);                 /* samples available (0 = none) */
void dcse_clear(void);

/* Called by hd_bank_load(): swap in the Dreamcast samples if this is one of
 * the mapped banks.  Returns the number of samples replaced. */
int dcse_apply(struct HdBank *b);
int dcse_last_applied(void);           /* what the last dcse_apply() replaced */

/* The DTPK file inside a Dreamcast disc image (.gdi, or the data track as
 * .bin / .iso) or SE_COMN.BIN itself, read into a malloc'd buffer.  NULL if
 * not found. */
uint8_t *dcse_read_disc(const char *path, size_t *size);

#endif
