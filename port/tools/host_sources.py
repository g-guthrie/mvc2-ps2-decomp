#!/usr/bin/env python3
"""Emit the credited C source lists for port/CMakeLists.txt.

usage: host_sources.py OUT.cmake [CHUNK]
Defines MVC2_GAME_SOURCES (config/matches.csv sources), MVC2_DATA_SOURCES
(config/data_matches.csv sources not already in the game list),
MVC2_HEADERS, and MVC2_CHUNK_<n> / MVC2_CHUNK_COUNT for batched filtering.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    out = Path(sys.argv[1])
    chunk = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    with open(ROOT / "config/matches.csv") as f:
        game = sorted({r["source"] for r in csv.DictReader(f) if r["source"].endswith(".c")})
    with open(ROOT / "config/data_matches.csv") as f:
        data = sorted({r["source"] for r in csv.DictReader(f) if r["source"].endswith(".c")} - set(game))
    heads = sorted(str(p.relative_to(ROOT)) for d in ("src", "src/data") for p in (ROOT / d).glob("*.h"))
    # Port J: data TUs in EE address order (the host link lays the EE data
    # image out contiguously, hostify R18), after the hole before the first.
    sys.path.insert(0, str(ROOT / "port/tools"))
    import link_catalog as L
    first = {}
    for u in L.layout_units():
        first.setdefault(u[3], u[0])
    data.sort(key=lambda s: (first.get(s, 1 << 32), s))
    import hostify
    start = out.parent / "ee_data_start.c"
    text0 = ("/* generated by port/tools/host_sources.py: the EE data image before the\n"
             "   first C data unit (VU1 microcode etc., zero on the host) */\n" + hostify.hole_text(None))
    # the holes (EE data with no C: tables, strings, microcode) as (EE address,
    # size): port/host/ee_image.c fills them at boot from the user's own
    # executable on the disc (no game bytes in the build)
    holes = sorted((lo, sz) for lo, sz, _ in L.data_holes().values() if sz > 0)
    text0 += ("const unsigned int mvc2_ee_holes[][2] = {\n" +
              "".join(f"  {{{lo:#010x}, {sz:#x}}},\n" for lo, sz in holes) + "};\n"
              f"const int mvc2_ee_nholes = {len(holes)};\n")
    if not start.exists() or start.read_text() != text0:
        start.write_text(text0)
    allsrc = game + data
    lines = ["# generated by port/tools/host_sources.py - do not edit"]

    def setl(name, items):
        lines.append(f"set({name}")
        lines.extend(f"  {i}" for i in items)
        lines.append(")")

    setl("MVC2_GAME_SOURCES", game)
    setl("MVC2_DATA_SOURCES", data)
    lines.append(f"set(MVC2_DATA_START {start})")
    setl("MVC2_HEADERS", heads)
    n = 0
    for i in range(0, len(allsrc), chunk):
        setl(f"MVC2_CHUNK_{n}", allsrc[i:i + chunk])
        n += 1
    lines.append(f"set(MVC2_CHUNK_COUNT {n})")
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)


if __name__ == "__main__":
    main()
